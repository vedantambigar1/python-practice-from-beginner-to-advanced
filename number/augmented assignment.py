#addition assignment operator
value = 10
value += 5

print(value) # 15

my_var = 10
my_var = my_var + 5

print(my_var) # 15

#subtraction assignment operator
count = 14
count -= 3

print(count) # 11

#multiplication assignment operator
product = 65
product *= 7

print(product) # 455

#division assignment operator

price = 100
price /= 4

print(price) # 25.0

#modulus assignment operator
total_pages = 23
total_pages //= 5

print(total_pages) # 4


