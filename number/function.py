#round()
value_1 = 4.798
value_2 = 4.253

rounded_int_1 = round(value_1)
rounded_int_2 = round(value_2, 1)

print(rounded_int_1)
print(rounded_int_2)

#abs()
num = -15

absolute_value = abs(num)
print(absolute_value) 

#pow()
result_1 = pow(2, 3)  # Equivalent to 2 ** 3
print(result_1)  # 8

result_2 = pow(2, 3, 5)  # (2 ** 3) % 5
print(result_2)  # 3